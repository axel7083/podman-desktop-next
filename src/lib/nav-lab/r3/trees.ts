/** systemd service generated by Quadlet for a unit file (podman-systemd.unit(5)). */
export function quadletService(file: string): string {
  const [base, type] = file.split('.');
  return type === 'container' || type === 'kube' ? `${base}.service` : `${base}-${type}.service`;
}

