/**
 * Icon rule: an extension root uses the extension logo; every child uses a
 * semantic icon (the core resource icon when it is one: Images, Pods…).
 * Every dashboard / overview, in the tree and in tabs, uses `OVERVIEW_ICON`.
 */
export const OVERVIEW_ICON: IconRef = faCircleInfo;

const overview = (detail = ''): Raw => ({ label: 'Overview', icon: OVERVIEW_ICON, detail });

export interface TreeNode {
  id: string;
  label: string;
  icon?: IconRef;
  status?: string;
  /** Dim text after the label. */
  detail?: string;
  /** Extra fields (quadlet type, service, path…). */
  data?: Record<string, string>;
  children?: TreeNode[];
}

export interface TreeProvider {
  id: string;
  /** Extension providing the tree (see `r3/exts.ts`). */
  extId: string;
  label: string;
  /** Extension logo (root icon). */
  icon: string;
  /** Connections the tree is contributed to. */
  connIds: string[];
  /** Flat sections of the dataset the tree replaces in P13. */
  replaces: string[];
  build: (connId: string) => Raw[];
}

export type Raw = Omit<TreeNode, 'id' | 'children'> & { children?: Raw[] };

